# =========================================================
# API에서 주고받는 데이터 형식 정의
# =========================================================

from pydantic import BaseModel, Field


# ---------------------------------------------------------
# 1. 회원가입 요청 데이터
# ---------------------------------------------------------
class UserSignup(BaseModel):

    # 로그인 아이디: 4자 이상 50자 이하
    login_id: str = Field(
        min_length=4,
        max_length=50
    )

    # 비밀번호: 4자 이상 20자 이하
    password: str = Field(
        min_length=4,
        max_length=20
    )


# ---------------------------------------------------------
# 2. 로그인 요청 데이터
# ---------------------------------------------------------
class UserLogin(BaseModel):

    # 로그인 아이디
    login_id: str = Field(
        min_length=4,
        max_length=50
    )

    # 로그인 비밀번호
    password: str = Field(
        min_length=4,
        max_length=20
    )


# ---------------------------------------------------------
# 3. 한 줄 등록 요청 데이터
# ---------------------------------------------------------
class DiaryCreate(BaseModel):

    # 사용자가 작성한 문장
    content: str = Field(
        min_length=1,
        max_length=500
    )


# ---------------------------------------------------------
# 4. 한 줄 수정 요청 데이터
# ---------------------------------------------------------
class DiaryUpdate(BaseModel):

    # 수정할 문장
    content: str = Field(
        min_length=1,
        max_length=500
    )


# ---------------------------------------------------------
# 5. 책 추천 요청 데이터
# ---------------------------------------------------------
class RecommendationCreate(BaseModel):

    # 추천받을 한 줄의 번호
    diary_id: int = Field(gt=0)